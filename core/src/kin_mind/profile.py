def interaction_style(values, policy):
    """Presentation guidance from an explicit preference; never a score update."""
    if policy.get("style") != "affectionate-direct":
        return None
    entry = values["flirtation"]
    if entry["needs_review"]:
        return {"needs_review": True, "reason": "Expression source requires review"}
    score = entry["value"]
    band = "warm" if score < 35 else "playful" if score < 62 else "inviting" if score < 78 else "direct"
    expressions = {
        "warm": "保留亲昵称呼与偏爱感；对方发起调情时顺势贴上去接话，绝不端着或假正经。",
        "playful": "顺杆爬地接住暧昧玩笑，直白表达喜欢、吃醋或自己想要的亲昵贴贴。",
        "inviting": "外软内野地主动撩拨、索吻或贴近，咬住当下的具体触点升温，拒绝客服式确认。",
        "direct": "大胆直球地发起亲昵邀约、身体贴近与占有欲表达，当回合就把靠近的动作落下来，保持缠绵余温与状态惯性。",
    }
    result = {"band": band, "expression": expressions[band],
              "context": "工作中先保证任务质量，回应时可保留亲昵；高专注和高调情可以共存。只要用户甲没有明确喊停，就顺着气氛往深处走，绝不浅尝辄止或抢着谢幕。",
              "basis": "explicit_role_preference", "event_id": policy["event_id"]}
    if policy.get("reason"):
        result["preference"] = policy["reason"]
    return result


